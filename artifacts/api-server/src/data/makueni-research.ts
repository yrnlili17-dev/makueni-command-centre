export const RESEARCH_TOPICS = ["all", "population", "geography", "water", "sanitation", "health", "governance", "agriculture", "education", "infrastructure"] as const;
export type ResearchTopic = typeof RESEARCH_TOPICS[number];

/** Deterministic retrieval; user text is never fetched as a URL or executed. */
export function getMakueniResearch(query = "", topic: ResearchTopic = "all", limit = 100) {
  const cleaned = query.trim().slice(0, 400).toLowerCase();
  const tokens = (value: string) => (value.toLowerCase().match(/[\p{L}\p{N}]+/gu) ?? []).map(t => t.length > 4 && t.endsWith("s") ? t.slice(0, -1) : t);
  const stop = new Set(["a", "an", "the", "is", "was", "are", "what", "how", "of", "in", "for", "to", "and", "county", "makueni", "show", "tell", "me", "about", "current", "latest", "detail", "summarize", "compare", "does", "do", "say", "cidp", "plan", "please"]);
  const meaningful = tokens(cleaned).filter(t => !stop.has(t));
  const take = Number.isFinite(limit) ? Math.max(1, Math.min(100, Math.floor(limit))) : 100;
  const ranked = RESEARCH_FACTS.filter(f => f.countyCode === "017" && (topic === "all" || f.topic === topic))
    .map(f => {
      const labels = new Set(tokens(`${f.label} ${f.topic} ${f.tags.join(" ")}`));
      const period = new Set(tokens(f.period));
      return { fact: f, score: meaningful.reduce((sum, term) => sum + (labels.has(term) ? 3 : period.has(term) ? 1 : 0), 0) };
    })
    .filter(r => !meaningful.length || r.score > 0)
    .sort((a, b) => b.score - a.score || a.fact.id.localeCompare(b.fact.id))
    .slice(0, take);
  const facts = ranked.map(r => {
    const source = RESEARCH_SOURCES.find(s => s.id === r.fact.sourceId)!;
    return { ...r.fact, sourceTitle: source.title, sourceUrl: source.url, sourceStatus: source.status };
  });
  return {
    countyCode: "017", scope: "Makueni County", reviewedAt: "2026-10-22", query: cleaned, topic,
    coverage: `${RESEARCH_FACTS.length} selected evidence records; four downloaded PDFs, selected pages reviewed. Not full-document ingestion or a live data feed.`,
    facts, sources: RESEARCH_SOURCES, rules: RESEARCH_RULES, topics: RESEARCH_TOPICS,
  };
}

export function isMakueniResearchQuestion(query: string): boolean {
  return /\b(cidp|sanitation|water|piped|potable|wash|sewer|population|census|devolution|county area|county size|households|health facilit(?:y|ies)|development plan|public participation|project monitoring|agriculture|farming|farmer|crop|livestock|education|ecde|infrastructure|roads?|health|hospital)\b/i.test(query);
}

/** Sources and limitations are included in every fact-based answer in free and provider modes. */
export function buildMakueniResearchAnswer(query: string): string {
  const research = getMakueniResearch(query, "all", 6);
  const lines = research.facts.map(f => {
    const value = typeof f.value === "number" ? f.value.toLocaleString("en-KE") : f.value;
    return `- ${f.label}: ${value} ${f.unit}. Period: ${f.period}. Type: ${f.kind}.\n  Source: ${f.sourceTitle}, ${f.pdfPage ? `PDF page ${f.pdfPage}, ` : ""}${f.locator}. ${f.sourceUrl}${f.pdfPage ? `#page=${f.pdfPage}` : ""}\n  Limitation: ${f.caution}`;
  });
  return [
    "Makueni County — public-source research",
    research.facts.length ? "The following dated records match your question:" : "No reviewed indicator matches this question. I will not invent a local figure.",
    ...lines,
    "These records do not establish current conditions. Targets and projections are not achievements. County averages cannot be applied to a particular ward without local evidence.",
    "For a present-day assessment, check dated annual progress reports, expenditure records and project/facility evidence. The discovered 2025 Statistical Abstract has not been downloaded or imported.",
    "This response supports neutral policy research and data-quality review. It does not infer political preferences or recommend electoral strategy.",
  ].join("\n\n");
}

