import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const configDir = path.join(root, "config");

const requiredFiles = [
  "campaign.json",
  "branding.json",
  "election.json",
  "geography.json",
  "ai.json"
];

function readJson(filename) {
  const filePath = path.join(configDir, filename);

  if (!fs.existsSync(filePath)) {
    throw new Error(`Missing configuration file: ${filename}`);
  }

  try {
    return JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch (error) {
    throw new Error(`Invalid JSON in ${filename}: ${error.message}`);
  }
}

for (const filename of requiredFiles) {
  readJson(filename);
}

const campaign = readJson("campaign.json");
const branding = readJson("branding.json");
const election = readJson("election.json");
const geography = readJson("geography.json");
const ai = readJson("ai.json");

const bundle = {
  campaign,
  branding,
  election,
  geography,
  ai
};

function createTypeScriptModule(targetPath, environment) {
  fs.mkdirSync(path.dirname(targetPath), { recursive: true });

  const content = `/*
 * AUTO-GENERATED FILE.
 * Generated by scripts/sync-campaign-config.mjs.
 * Edit files inside /config and rerun the sync script.
 */

export const CAMPAIGN_CONFIG = ${JSON.stringify(campaign, null, 2)} as const;

export const BRANDING_CONFIG = ${JSON.stringify(branding, null, 2)} as const;

export const ELECTION_CONFIG = ${JSON.stringify(election, null, 2)} as const;

export const GEOGRAPHY_CONFIG = ${JSON.stringify(geography, null, 2)} as const;

export const AI_CONFIG = ${JSON.stringify(ai, null, 2)} as const;

export const CONFIG_BUNDLE = {
  campaign: CAMPAIGN_CONFIG,
  branding: BRANDING_CONFIG,
  election: ELECTION_CONFIG,
  geography: GEOGRAPHY_CONFIG,
  ai: AI_CONFIG
} as const;

export const CANDIDATE_NAME =
  CAMPAIGN_CONFIG.candidate.fullName;

export const CANDIDATE_SHORT_NAME =
  CAMPAIGN_CONFIG.candidate.shortName;

export const CAMPAIGN_NAME =
  CAMPAIGN_CONFIG.campaign.name;

export const CAMPAIGN_PARTY =
  CAMPAIGN_CONFIG.campaign.party;

export const CAMPAIGN_POSITION =
  CAMPAIGN_CONFIG.candidate.position;

export const CAMPAIGN_COUNTY =
  CAMPAIGN_CONFIG.candidate.county;

export const CAMPAIGN_SLOGAN =
  CAMPAIGN_CONFIG.campaign.slogan;

export const CONSTITUENCIES =
  GEOGRAPHY_CONFIG.constituencies;

export const WARDS =
  GEOGRAPHY_CONFIG.constituencies.flatMap(
    constituency =>
      constituency.wards.map(ward => ({
        ...ward,
        constituencyId: constituency.id,
        constituencyName: constituency.name
      }))
  );

export function getConstituencyById(id: string) {
  return CONSTITUENCIES.find(
    constituency => constituency.id === id
  );
}

export function getWardById(id: string) {
  return WARDS.find(ward => ward.id === id);
}

export function getWardsByConstituency(
  constituencyId: string
) {
  return WARDS.filter(
    ward => ward.constituencyId === constituencyId
  );
}

export const CONFIG_ENVIRONMENT = ${JSON.stringify(environment)} as const;
`;

  fs.writeFileSync(targetPath, content, "utf8");
  console.log(`GENERATED ${path.relative(root, targetPath)}`);
}

createTypeScriptModule(
  path.join(
    root,
    "artifacts/api-server/src/config/campaign-config.ts"
  ),
  "server"
);

createTypeScriptModule(
  path.join(
    root,
    "artifacts/commandcentre/src/config/campaign-config.ts"
  ),
  "client"
);

const bundleTarget = path.join(
  root,
  "config/generated-config-bundle.json"
);

fs.writeFileSync(
  bundleTarget,
  `${JSON.stringify(bundle, null, 2)}\n`,
  "utf8"
);

console.log(
  `GENERATED ${path.relative(root, bundleTarget)}`
);

console.log("\nCampaign configuration sync completed.");
console.log(
  `Candidate: ${campaign.candidate.fullName}`
);
console.log(
  `Campaign: ${campaign.campaign.name}`
);
console.log(
  `Party: ${campaign.campaign.party}`
);
console.log(
  `Position: ${campaign.candidate.position}`
);
console.log(
  `Constituencies: ${geography.constituencies.length}`
);
console.log(
  `Wards: ${geography.constituencies.reduce(
    (total, constituency) =>
      total + constituency.wards.length,
    0
  )}`
);
